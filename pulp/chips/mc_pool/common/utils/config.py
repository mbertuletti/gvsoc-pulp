"""
Generate the C (mc_cluster_arch.h) and assembly (mc_cluster_arch.inc) headers
describing a multi-cluster MemPool configuration, for the MemPool runtime.

The MemPool runtime comes with the headers of its default configuration. When
the software runs on a different configuration, generate the headers with this
tool and point the runtime to them:

    NUM_CORES=512 python3 config.py tensorpool <out_dir>
    make <app> MC_ARCH_DIR=<out_dir> ...

The tensorpool configuration reads NUM_CORES, NUM_REDMULE_TILES, REDMULE_HEIGHT,
REDMULE_WIDTH and TE_QUEUE_DEPTH from the environment, as the gvsoc model does.
"""

import argparse
import ast
import importlib.util
import math
import os

parser = argparse.ArgumentParser(
    description="Generate the C and assembly headers of a multi-cluster MemPool configuration.")
parser.add_argument("config", help="Configuration name (key into mc_pool_arch_base.CONFIGS)")
parser.add_argument("out_dir", help="Path to the output directory for header files")
parser.add_argument("--param", action="append", default=[], metavar="KEY=VALUE",
                    help="Override an individual arch attribute (repeatable)")
args = parser.parse_args()

# Load mc_pool_arch_base.py by file path, relative to this script, so that this
# tool works standalone regardless of the caller's PYTHONPATH
_this_dir = os.path.dirname(os.path.abspath(__file__))
_arch_base_path = os.path.normpath(os.path.join(_this_dir, '..', '..', 'mc_pool_arch_base.py'))
_spec = importlib.util.spec_from_file_location('mc_pool_arch_base', _arch_base_path)
_arch_base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_arch_base)

if args.config not in _arch_base.CONFIGS:
    raise SystemExit(
        f"Unknown configuration '{args.config}', expected one of: "
        f"{sorted(_arch_base.CONFIGS.keys())}")

# Values given with --param are Python literals (e.g. 0x1000, [0, 2, 0, 2]),
# anything else is taken as a string
overrides = {}
for item in args.param:
    key, _, value = item.partition('=')
    try:
        overrides[key] = ast.literal_eval(value)
    except (ValueError, SyntaxError):
        overrides[key] = value

# Instantiate the configuration, so that the values it computes (e.g. from
# NUM_CORES) are the ones the gvsoc model uses
arch = _arch_base.CONFIGS[args.config](**overrides)
attributes = vars(arch)


def header_value(value):
    """Value as written in the headers (hex for addresses and sizes)."""
    if isinstance(value, bool):
        return str(int(value))
    if isinstance(value, int):
        return hex(value) if value >= 0x10000 else str(value)
    if isinstance(value, list):
        return '{' + ', '.join(header_value(v) for v in value) + '}'
    return str(value)


environment = ' '.join(f'{name}={os.environ[name]}' for name in
    ('NUM_CORES', 'NUM_REDMULE_TILES', 'REDMULE_HEIGHT', 'REDMULE_WIDTH', 'TE_QUEUE_DEPTH')
    if name in os.environ)
command = ' '.join(['python3 config.py', args.config, '<out_dir>'] +
                   [f'--param {item}' for item in args.param])

license = (
	f'Copyright 2022 ETH Zurich and University of Bologna.\n'
	f'Licensed under the Apache License, Version 2.0, see LICENSE for details.\n'
	f'SPDX-License-Identifier: Apache-2.0\n')

banner = (
    f'Multi-cluster MemPool architecture: configuration "{args.config}"\n'
    f'Generated by pulp/chips/mc_pool/common/utils/config.py in GVSoC:\n'
    f'  {environment + " " if environment else ""}{command}\n'
    f'Build the MemPool software for another configuration with headers generated\n'
    f'the same way, passed with make MC_ARCH_DIR=<out_dir>\n')

os.makedirs(args.out_dir, exist_ok=True)

# C header
c_header = ''.join(f'// {line}'.rstrip() + '\n' for line in license.splitlines()) + '\n'
c_header += ''.join(f'// {line}'.rstrip() + '\n' for line in banner.splitlines()) + '\n'
c_header += '#ifndef MC_CLUSTER_ARCH_H\n'
c_header += '#define MC_CLUSTER_ARCH_H\n\n'
for attr_name, attr_value in attributes.items():
    if attr_value is None:
        continue
    c_header += f'#define ARCH_{attr_name.upper()} {header_value(attr_value)}\n'
c_header += '\n#endif // MC_CLUSTER_ARCH_H\n'

# Assembly header, included with .include and so not preprocessed, without the
# lists, plus the log2 of the stack size of each core
s_header = ''.join(f'# {line}'.rstrip() + '\n' for line in license.splitlines()) + '\n'
s_header += ''.join(f'# {line}'.rstrip() + '\n' for line in banner.splitlines()) + '\n'
for attr_name, attr_value in attributes.items():
    if attr_value is None or isinstance(attr_value, list):
        continue
    if attr_name == 'cluster_stack_size':
        stack_size_per_core = attr_value / (1 << (arch.num_core_per_cluster - 1).bit_length())
        s_header += f'.set ARCH_CLUSTER_STACK_OFFSET, {int(math.ceil(math.log2(stack_size_per_core)))}\n'
    s_header += f'.set ARCH_{attr_name.upper()}, {header_value(attr_value)}\n'

for file_name, content in (('mc_cluster_arch.h', c_header), ('mc_cluster_arch.inc', s_header)):
    path = os.path.join(args.out_dir, file_name)
    # Only (over)write the file when its content changes, so that the software
    # is not needlessly recompiled
    if os.path.exists(path) and open(path).read() == content:
        print(f'Header file "{path}" already up to date.')
        continue
    with open(path, 'w') as file:
        file.write(content)
    print(f'Header file "{path}" generated successfully.')
